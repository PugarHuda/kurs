// Writes docs/evidence.md from deployments/*.json plus the latest on-chain round of every feed.
// Run: cd reporter && npm run evidence
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createPublicClient, http, keccak256, toBytes } from "viem";

const oracleAbi = JSON.parse(readFileSync("../contracts/out/KursOracle.sol/KursOracle.json", "utf8")).abi;

const NETS = {
  portaldot: {
    label: "Portaldot V3 testnet",
    rpc: "https://test-evm-rpc-v3.portaldot.dev",
    // the Substrate explorer does not resolve EVM hashes or H160s: link the block in the Node Console
    tx: (h, block) => `https://node-console.portaldot.dev/?rpc=wss%3A%2F%2Ftest-node-v3.portaldot.dev#/explorer/query/${block}`,
    addr: () => null,
  },
  sepolia: {
    label: "Ethereum Sepolia",
    rpc: "https://ethereum-sepolia-rpc.publicnode.com",
    tx: (h) => `https://sepolia.etherscan.io/tx/${h}`,
    addr: (a) => `https://sepolia.etherscan.io/address/${a}`,
  },
};

const short = (x) => `${x.slice(0, 10)}…${x.slice(-6)}`;
/** markdown cell: a link when the network has an explorer for it, plain code otherwise */
const cell = (url, text) => (url ? `[\`${text}\`](${url})` : `\`${text}\``);
const deployments = readdirSync("../deployments")
  .filter((f) => f.endsWith(".json") && !f.startsWith("local"))
  .map((f) => JSON.parse(readFileSync(`../deployments/${f}`, "utf8")))
  .sort((a, b) => (a.chain === "portaldot" ? -1 : b.chain === "portaldot" ? 1 : 0));

let md = `# On-chain evidence

Generated by \`npm run evidence\` in reporter/ on ${new Date().toISOString()} from \`deployments/*.json\` and live RPC reads.
Every link opens a public explorer.

`;

const latestBy = {};
for (const d of deployments) {
  const n = NETS[d.chain];
  const c = createPublicClient({ transport: http(n.rpc) });
  md += `## ${n.label} (chain id ${d.chainId})\n\n`;
  md += `| Contract | Address |\n|---|---|\n`;
  md += `| KursOracle | ${cell(n.addr(d.oracle), d.oracle)} |\n`;
  md += `| KursAggregatorFactory | ${cell(n.addr(d.factory), d.factory)} |\n`;
  if (d.converter) md += `| KursConverter (ERC-7412 pull consumer, USD/IDR) | ${cell(n.addr(d.converter), d.converter)} |\n`;
  if (d.kursRemit) md += `| KursRemit (ink! v6) | ${cell(n.addr(d.kursRemit), d.kursRemit)} |\n`;
  if (d.quoteOracle) md += `| KursQuoteOracle (ERC-7726 getQuote: BTC, ETH, USD, IDR, pivots through USD) | ${cell(n.addr(d.quoteOracle), d.quoteOracle)} |\n`;
  if (d.pyth) md += `| KursPyth (Pyth IPyth: getPrice, updatePriceFeeds with Kurs bundles) | ${cell(n.addr(d.pyth), d.pyth)} |\n`;
  if (d.morphoOracleBtcIdr) md += `| KursMorphoOracle (Morpho Blue IOracle, BTC collateral / Rupiah loan token) | ${cell(n.addr(d.morphoOracleBtcIdr), d.morphoOracleBtcIdr)} |\n`;
  if (d.chain === "portaldot")
    md += `\nThe same prices read through the Substrate runtime API \`ReviveApi_call\` (node WebSocket, no EVM RPC): [/api/substrate](https://kurs-ten-zeta.vercel.app/api/substrate), or \`npx tsx scripts/substrate-read.ts\` in reporter/, which also checks they match the EVM RPC.\n`;
  const owner = await c.readContract({ address: d.oracle, abi: oracleAbi, functionName: "owner" }).catch(() => null);
  if (d.governance) {
    const g = d.governance;
    const isMs = owner && owner.toLowerCase() === g.h160.toLowerCase();
    const block = (h) => `https://node-console.portaldot.dev/?rpc=wss%3A%2F%2Ftest-node-v3.portaldot.dev#/explorer/query/${h}`;
    md += `\n### Governance: ${g.type}\n\n`;
    md += `\`owner()\` read live: \`${owner}\` ${isMs ? "**= the multisig account**" : "(not the multisig)"}. `;
    md += `Changing feeds, reporters or ownership needs ${g.threshold} of ${g.signatories.length} ${g.type.startsWith("pallet-multisig") ? "Substrate signers" : "Safe owners"}: ${g.signatories.map((s) => `\`${s}\``).join(", ")}. `;
    if (g.substrateTxs) {
      md += `Multisig account \`${g.account}\`, its Revive address \`${g.h160}\`.\n\n| Step | Extrinsic |\n|---|---|\n`;
      for (const [what, t] of Object.entries(g.substrateTxs)) md += `| ${what} | ${t.block ? `[\`${short(t.hash)}\`](${block(t.block)})` : `\`${short(t.hash)}\``} |\n`;
      if (g.timelock?.pure) {
        const t = g.timelock;
        const live = owner && t.pureH160 && owner.toLowerCase() === t.pureH160.toLowerCase();
        md += `\n#### Timelock: pallet-proxy delay of ${t.delayBlocks} blocks (~${Math.round((t.delayBlocks * 6) / 60)} min)\n\n`;
        md += `Ownership moves to pure proxy \`${t.pure}\` (Revive \`${t.pureH160}\`), controlled by the multisig with a ${t.delayBlocks}-block delay: every owner action is announced (2 of 3), can execute only after the delay, and can be vetoed with \`proxy.rejectAnnouncement\` meanwhile. Status: ${live ? "**active, `owner()` is the pure proxy**" : `announced at block #${t.announcedAt}, executable from #${t.announcedAt + t.delayBlocks}`}.\n\n| Step | Extrinsic |\n|---|---|\n`;
        for (const [what, s] of Object.entries(t.steps)) {
          const one = s.execute ?? s;
          md += `| ${what} | [\`${short(one.hash)}\`](${block(one.block)})${s.approve ? ` (approved [\`${short(s.approve.hash)}\`](${block(s.approve.block)}))` : ""} |\n`;
        }
        for (const [what, r] of Object.entries(t.rejectedEarly ?? {}))
          md += `| rejected on chain, as intended: ${what} → \`${r.error}\` | ${r.block ? `[\`${short(r.hash)}\`](${block(r.block)})` : `\`${short(r.hash)}\``} |\n`;
      }
    } else {
      md += `Safe ${cell(n.addr(g.account), g.account)} (also in the Safe app: https://app.safe.global/home?safe=sep:${g.account}). The handoff transactions are listed below.\n`;
    }
  } else if (owner) {
    md += `\n\`owner()\`: \`${owner}\`\n`;
  }
  md += `\nReporters (quorum ${d.quorum} of ${d.reporters.length}): ${d.reporters.map((r) => `${cell(n.addr(r), short(r))}`).join(", ")}\n\n`;

  md += `### Feeds and latest round\n\n| Feed | AggregatorV3 clone | Latest round | Answer | Updated (UTC) |\n|---|---|---|---|---|\n`;
  latestBy[d.chain] = {};
  for (const [pair, agg] of Object.entries(d.aggregators)) {
    const [roundId, answer, , updatedAt] = await c
      .readContract({ address: d.oracle, abi: oracleAbi, functionName: "latestRound", args: [keccak256(toBytes(pair))] })
      .catch(() => [0n, 0n, 0n, 0n]);
    latestBy[d.chain][pair] = { roundId, answer };
    const when = updatedAt ? new Date(Number(updatedAt) * 1000).toISOString().replace("T", " ").slice(0, 19) : "none yet";
    md += `| ${pair} | ${cell(n.addr(agg), short(agg))} | ${roundId} | ${(Number(answer) / 1e8).toString()} | ${when} |\n`;
  }

  if (d.aggregatorsV2) {
    md += `\n### Chainlink V2 + V3 aggregators (\`latestAnswer\` for Aave V3's AaveOracle)\n\n| Feed | KursAggregatorV2V3 | latestAnswer() |\n|---|---|---|\n`;
    const v2 = [{ type: "function", name: "latestAnswer", stateMutability: "view", inputs: [], outputs: [{ type: "int256" }] }];
    for (const [pair, a] of Object.entries(d.aggregatorsV2)) {
      const ans = await c.readContract({ address: a, abi: v2, functionName: "latestAnswer" }).catch(() => null);
      md += `| ${pair} | ${cell(n.addr(a), short(a))} | ${ans === null ? "n/a" : ans.toString()} |\n`;
    }
  }
  if (d.pyth) {
    const pythAbi = [{ type: "function", name: "getPriceUnsafe", stateMutability: "view", inputs: [{ type: "bytes32" }], outputs: [{ type: "tuple", components: [{ name: "price", type: "int64" }, { name: "conf", type: "uint64" }, { name: "expo", type: "int32" }, { name: "publishTime", type: "uint256" }] }] }];
    const priceAbi = [{ type: "function", name: "price", stateMutability: "view", inputs: [], outputs: [{ type: "uint256" }] }];
    md += `\n### Pyth and Morpho views (read live)\n\n| Call | Result |\n|---|---|\n`;
    for (const pair of ["BTC/USD", "USD/IDR"]) {
      const p = await c.readContract({ address: d.pyth, abi: pythAbi, functionName: "getPriceUnsafe", args: [keccak256(toBytes(pair))] }).catch(() => null);
      md += `| \`KursPyth.getPriceUnsafe(keccak256("${pair}"))\` | ${p ? `price ${p.price}, expo ${p.expo} (= ${Number(p.price) * 10 ** p.expo}), conf ${p.conf}, publishTime ${new Date(Number(p.publishTime) * 1000).toISOString()}` : "n/a"} |\n`;
    }
    if (d.morphoOracleBtcIdr) {
      const mp = await c.readContract({ address: d.morphoOracleBtcIdr, abi: priceAbi, functionName: "price" }).catch(() => null);
      md += `| \`KursMorphoOracle.price()\` | ${mp === null ? "reverts: a leg is older than the quote oracle's maxAge (ERC-7412 OracleDataRequired)" : `${mp} (1 BTC = Rp ${(Number((mp * 10n ** 8n) / 10n ** 36n) / 100).toLocaleString("en-US")})`} |\n`;
    }
  }
  md += `\n### Transactions\n\n| What | Transaction |\n|---|---|\n`;
  for (const [what, h] of Object.entries(d.txs)) {
    const rc = await c.getTransactionReceipt({ hash: h }).catch(() => null);
    md += `| ${what} | ${cell(n.tx(h, rc?.blockNumber), short(h))}${rc ? ` (block ${rc.blockNumber})` : ""} |\n`;
  }
  md += "\n";
}

if (deployments.length > 1) {
  const [a, b] = deployments;
  md += `## Same signed round on ${NETS[a.chain].label} and ${NETS[b.chain].label}\n\n| Feed | Round | ${NETS[a.chain].label} | ${NETS[b.chain].label} | Identical |\n|---|---|---|---|---|\n`;
  for (const pair of Object.keys(a.aggregators)) {
    const x = latestBy[a.chain][pair];
    const y = latestBy[b.chain][pair];
    if (!x || !y) continue;
    const same = x.roundId === y.roundId && x.answer === y.answer;
    md += `| ${pair} | ${x.roundId} / ${y.roundId} | ${Number(x.answer) / 1e8} | ${Number(y.answer) / 1e8} | ${same ? "yes" : "different round"} |\n`;
  }
  md += "\n";
}

md += `## Source verification

Sepolia contracts are verified on Sourcify with an exact match:
${deployments
  .filter((d) => d.chain === "sepolia")
  .map((d) =>
    [d.oracle, d.factory, d.converter, d.quoteOracle, d.pyth, d.morphoOracleBtcIdr, ...Object.values(d.aggregatorsV2 ?? {})]
      .filter(Boolean)
      .map((a) => `- https://repo.sourcify.dev/contracts/full_match/11155111/${a}/`)
      .join("\n"),
  )
  .join("\n")}

To check any deployment yourself: \`cd contracts && forge build\`, then compare \`out/KursOracle.sol/KursOracle.json\` deployedBytecode with \`eth_getCode\` at the oracle address (immutables differ only in DOMAIN_SEPARATOR).
`;

writeFileSync(process.env.EVIDENCE_OUT ?? "../docs/evidence.md", md);
console.log("docs/evidence.md written");
