// Regenerates reporter/src/abi.ts from Foundry artifacts (web imports it from there).
import { readFileSync, writeFileSync } from "node:fs";
const art = (file, name) => JSON.parse(readFileSync(`contracts/out/${file}.sol/${name}.json`, "utf8"));
const items = {
  kursOracleAbi: art("KursOracle", "KursOracle").abi,
  kursAggregatorAbi: art("KursAggregatorV3", "KursAggregatorV3").abi,
  kursFactoryAbi: art("KursAggregatorV3", "KursAggregatorFactory").abi,
  kursConverterAbi: art("KursConverter", "KursConverter").abi,
  kursQuoteAbi: art("KursQuoteOracle", "KursQuoteOracle").abi,
  kursAggregatorV2V3Abi: art("KursAggregatorV2V3", "KursAggregatorV2V3").abi,
  kursPythAbi: art("KursPyth", "KursPyth").abi,
  kursMorphoOracleAbi: art("KursMorphoOracle", "KursMorphoOracle").abi,
  kursDiaAbi: art("KursDIA", "KursDIA").abi,
  kursBandAbi: art("KursBand", "KursBand").abi,
  kursApi3Abi: art("KursApi3", "KursApi3ReaderProxy").abi,
  kursChronicleAbi: art("KursChronicle", "KursChronicle").abi,
  kursAaveOracleAbi: art("KursAaveOracle", "KursAaveOracle").abi,
  kursSiloOracleAbi: art("KursSiloOracle", "KursSiloOracle").abi,
  kursTwapAbi: art("KursTwap", "KursTwap").abi,
};
const bytecode = {
  kursOracleBytecode: art("KursOracle", "KursOracle").bytecode.object,
  kursFactoryBytecode: art("KursAggregatorV3", "KursAggregatorFactory").bytecode.object,
  kursConverterBytecode: art("KursConverter", "KursConverter").bytecode.object,
  kursQuoteBytecode: art("KursQuoteOracle", "KursQuoteOracle").bytecode.object,
  kursAggregatorV2V3Bytecode: art("KursAggregatorV2V3", "KursAggregatorV2V3").bytecode.object,
  kursPythBytecode: art("KursPyth", "KursPyth").bytecode.object,
  kursMorphoOracleBytecode: art("KursMorphoOracle", "KursMorphoOracle").bytecode.object,
  kursDiaBytecode: art("KursDIA", "KursDIA").bytecode.object,
  kursBandBytecode: art("KursBand", "KursBand").bytecode.object,
  kursApi3Bytecode: art("KursApi3", "KursApi3ReaderProxy").bytecode.object,
  kursChronicleBytecode: art("KursChronicle", "KursChronicle").bytecode.object,
  kursAaveOracleBytecode: art("KursAaveOracle", "KursAaveOracle").bytecode.object,
  kursSiloOracleBytecode: art("KursSiloOracle", "KursSiloOracle").bytecode.object,
  kursTwapBytecode: art("KursTwap", "KursTwap").bytecode.object,
};
let src = "// generated by scripts/gen-abi.mjs from contracts/out — do not edit\n";
for (const [k, v] of Object.entries(items)) src += `export const ${k} = ${JSON.stringify(v)} as const;\n`;
writeFileSync("reporter/src/abi.ts", src + Object.entries(bytecode).map(([k, v]) => `export const ${k} = "${v}" as const;\n`).join(""));
console.log("abi written");

// sdk/src/generated.ts: ABIs (no bytecode) and the live addresses, for the npm package
const dep = (c) => JSON.parse(readFileSync(`deployments/${c}.json`, "utf8"));
const pick = (d) => {
  const o = { chainId: d.chainId, oracle: d.oracle, factory: d.factory, aggregators: d.aggregators };
  for (const k of ["converter", "quoteOracle", "pyth", "morphoOracleBtcIdr", "aggregatorsV2", "dia", "band", "api3", "chronicle", "aaveOracle", "siloOracle", "twap"]) if (d[k]) o[k] = d[k];
  return o;
};
const sdkAbis = ["kursOracleAbi", "kursAggregatorAbi", "kursAggregatorV2V3Abi", "kursQuoteAbi", "kursPythAbi", "kursMorphoOracleAbi", "kursConverterAbi", "kursDiaAbi", "kursBandAbi", "kursApi3Abi", "kursChronicleAbi", "kursAaveOracleAbi", "kursSiloOracleAbi", "kursTwapAbi"];
let sdk = "// generated by scripts/gen-abi.mjs from contracts/out and deployments/ — do not edit\n";
for (const k of sdkAbis) sdk += `export const ${k} = ${JSON.stringify(items[k])} as const;\n`;
sdk += `export const deployments = ${JSON.stringify({ portaldot: pick(dep("portaldot")), sepolia: pick(dep("sepolia")) }, null, 2)} as const;\n`;
writeFileSync("sdk/src/generated.ts", sdk);
console.log("sdk/src/generated.ts written");
